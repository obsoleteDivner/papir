// Interface language. The source strings are Ukrainian; English comes from
// the table below. Static markup is translated once at start (text and
// titles that match a source string), strings built in code go through t().

export type Lang = "uk" | "en";

export const lang: Lang = pick();

/** A choice made in the menu wins, then ?lang= (WOPI hosts pass it), then the browser. */
function pick(): Lang {
  let saved: string | null = null;
  try {
    saved = localStorage.getItem("papir:lang");
  } catch {
    /* ignore */
  }
  const want = (saved || new URLSearchParams(location.search).get("lang") || navigator.language || "uk").toLowerCase();
  return /^(uk|ru|be)/.test(want) ? "uk" : "en";
}

export function setLang(l: Lang): void {
  try {
    localStorage.setItem("papir:lang", l);
  } catch {
    /* ignore */
  }
  location.reload();
}

/** A string in the interface language; {0}, {1}… take the arguments. */
export function t(s: string, ...args: unknown[]): string {
  const out = lang === "en" ? EN[s] ?? s : s;
  return args.length ? out.replace(/\{(\d+)\}/g, (_, i) => String(args[Number(i)])) : out;
}

/** Translates the static page: text, titles and placeholders that match a source string. */
export function translatePage(root: ParentNode = document.body): void {
  document.documentElement.lang = lang;
  if (lang === "uk") return;
  const walk = document.createTreeWalker(root as Node, NodeFilter.SHOW_TEXT);
  for (let n = walk.nextNode(); n; n = walk.nextNode()) {
    const raw = n.nodeValue ?? "";
    const key = raw.trim();
    const en = key ? EN[key] : undefined;
    if (en) n.nodeValue = raw.replace(key, en);
  }
  for (const el of (root as Element).querySelectorAll?.("[title], [placeholder], [aria-label]") ?? []) {
    for (const a of ["title", "placeholder", "aria-label"]) {
      const v = el.getAttribute(a);
      const en = v ? EN[v] : undefined;
      if (en) el.setAttribute(a, en);
    }
  }
  const title = EN[document.title];
  if (title) document.title = title;
}

